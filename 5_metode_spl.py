# 4. METODE GAUSS-JORDAN
# ==========================================
def gauss_jordan(A, b):
  A = np.array(A, dtype=float)
  b = np.array(b, dtype=float)
  n = len(b)
  Ab = np.column_stack((A, b))

  for i in range(n):
    pivot = Ab[i, i]
    if pivot == 0:
      raise ValueError('Pivot nol terdeteksi.')
    Ab[i, :] /= pivot
    for j in range(n):
      if j != i:
        factor = Ab[j, i]
        Ab[j, :] -= factor * Ab[i, :]

  return Ab[:, -1]


