import time
import numpy as np


# ==========================================
# 1. METODE JACOBI
# ==========================================
def jacobi(A, b, tol=1e-5, max_iter=100):
  start_time = time.time()
  A = np.array(A, dtype=float)
  b = np.array(b, dtype=float)
  n = len(A)

  xlama = np.zeros(n)
  for i in range(n):
    xlama[i] = b[i] / A[i, i]

  C = -A.copy()
  for i in range(n):
    C[i, i] = 0.0
    C[i, :] = C[i, :] / A[i, i]

  d = xlama.copy()

  i = 1
  while i <= max_iter:
    xbaru = np.dot(C, xlama) + d
    if np.max(np.abs(xbaru - xlama)) <= tol:
      print(f'Jacobi konverge dalam waktu: {time.time() - start_time:.6f} detik')
      return xbaru
    else:
      xlama = xbaru.copy()
    i += 1

  print('Jacobi tidak konverge')
  return xlama


