# 2. METODE GAUSS-SEIDEL
# ==========================================
def gauss_seidel(A, b, tol=1e-5, max_iter=100):
  start_time = time.time()
  A = np.array(A, dtype=float)
  b = np.array(b, dtype=float)
  n = len(b)
  x = np.zeros(n)

  for iteration in range(1, max_iter + 1):
    x_new = np.copy(x)
    for i in range(n):
      s = sum(A[i, j] * x_new[j] for j in range(n) if j != i)
      x_new[i] = (b[i] - s) / A[i, i]

    if np.max(np.abs(x_new - x)) <= tol:
      print(
          'Gauss-Seidel konverge dalam waktu:'
          f' {time.time() - start_time:.6f} detik'
      )
      return x_new
    x = x_new

  print('Gauss-Seidel tidak konverge')
  return x


